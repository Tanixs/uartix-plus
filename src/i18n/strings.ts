export function getLocale(): Locale {
  try {
    const s = JSON.parse(localStorage.getItem("vs.settings") ?? "{}") as { locale?: Locale };
    return s.locale === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

export function t(key: string): string {
  const loc = getLocale();
  return (loc === "en" ? en[key] : zh[key]) ?? zh[key] ?? key;
}
