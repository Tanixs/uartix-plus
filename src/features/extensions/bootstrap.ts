/**
 * P174-A3：扩展宿主的引导脚本（bootstrap）。
 *
 * 它是被 `node --permission … bootstrap.mjs <pluginDir>` 直接执行的**普通 Node 脚本**，
 * 职责只有四件：握手、把 `ctx` 交给插件的 `activate()`、路由 `call`、按逆序跑 disposer。
 *
 * **必须说清楚的一件事：`ctx` 不是安全边界。**
 * 引导脚本与插件代码在**同一个进程、同一个 realm** 里，插件随时可以
 * `import("node:fs")` 绕过 `ctx.fs`。真正的边界只有两个：Node 的 `--allow-fs-write`
 * （内核级，拦得住）和批准卡（知情）。把 `ctx` 当成牢笼会让后面维护的人放松警惕——
 * 这与详设 §10.1 的口径一致：**护栏那一层被整层撤掉了，不要偷偷加回来**。
 *
 * 为什么是字符串而不是 .mjs 文件：它要和 `protocol.ts` 的字段名保持同源，而打成资源文件
 * 会多一条"资源没打进去"的故障路径。首次启动时写到 `<appDir>/ext-host/bootstrap.mjs`。
 */

/** 引导脚本源码。用数组 join 而不是模板串：里面全是反引号与 `${}`，模板串会被当场求值。 */
const LINES: string[] = [
  'import { createInterface } from "node:readline";',
  'import { pathToFileURL } from "node:url";',
  'import path from "node:path";',
  'import fs from "node:fs";',
  'import { spawn } from "node:child_process";',
  "",
  "const PROTOCOL = 1;",
  "const pluginDir = process.argv[2];",
  "if (!pluginDir) {",
  '  process.stderr.write("[bootstrap] 缺少 pluginDir\\n");',
  "  process.exit(2);",
  "}",
  "",
  "let token = null;",
  "let workspace = \"\";",
  "let ctx = null;",
  "const disposers = [];",
  "const panelHandlers = new Map();",
  "const tools = [];",
  "const children = new Set();",
  "",
  "function send(m) {",
  "  try { process.stdout.write(JSON.stringify(m) + \"\\n\"); } catch (e) { /* 管道断了，进程本来就要退 */ }",
  "}",
  "function log(level, msg) {",
  "  send({ t: \"log\", token, level, msg: String(msg).slice(0, 4000) });",
  "}",
  "",
  "/** 展开到绝对路径；越界（.. / 绝对路径）直接抛——这是便利检查，不是安全边界。 */",
  "function inside(rel) {",
  "  const full = path.resolve(pluginDir, rel);",
  "  const root = path.resolve(pluginDir) + path.sep;",
  "  if (full !== path.resolve(pluginDir) && !full.startsWith(root)) {",
  "    throw new Error(\"路径越界: \" + rel);",
  "  }",
  "  return full;",
  "}",
  "",
  "function makeCtx() {",
  "  const api = {",
  "    protocol: PROTOCOL,",
  "    get workspace() { return workspace; },",
  "    pluginDir,",
  "    log: {",
  "      debug: (m) => log(\"debug\", m),",
  "      info: (m) => log(\"info\", m),",
  "      warn: (m) => log(\"warn\", m),",
  "      error: (m) => log(\"error\", m),",
  "    },",
  "    onDispose(fn) {",
  "      if (typeof fn === \"function\") disposers.push(fn);",
  "    },",
  "    panels: {",
  "      register(id, handlers) {",
  "        panelHandlers.set(String(id), handlers || {});",
  "      },",
  "      emit(panelId, event, payload) {",
  "        send({ t: \"emit\", token, panelId: String(panelId), event: String(event), payload });",
  "      },",
  "    },",
  "    commands: {",
  "      handlers: new Map(),",
  "      register(id, fn) { this.handlers.set(String(id), fn); },",
  "      async run(id, args) {",
  "        const fn = this.handlers.get(String(id));",
  "        if (!fn) throw Object.assign(new Error(\"没有这个命令: \" + id), { code: \"not_found\" });",
  "        return await fn(args);",
  "      },",
  "    },",
  "    fs: {",
  "      resolve: inside,",
  "      readText(p) { return fs.promises.readFile(inside(p), \"utf8\"); },",
  "      readB64(p) { return fs.promises.readFile(inside(p)).then((b) => b.toString(\"base64\")); },",
  "      async list(p) {",
  "        const ents = await fs.promises.readdir(inside(p), { withFileTypes: true });",
  "        return ents.map((e) => ({ name: e.name, dir: e.isDirectory() }));",
  "      },",
  "      writeText(p, s) { return fs.promises.writeFile(inside(p), String(s), \"utf8\"); },",
  "      exists(p) { return fs.existsSync(inside(p)); },",
  "    },",
  "    process: {",
  "      spawn(opts) {",
  "        const child = spawn(opts.cmd, opts.args || [], {",
  "          cwd: opts.cwd || pluginDir,",
  "          env: { ...process.env, ...(opts.env || {}) },",
  "          windowsHide: true,",
  "        });",
  "        children.add(child);",
  "        const job = {",
  "          pid: child.pid,",
  "          kill(signal) { try { child.kill(signal || \"SIGTERM\"); } catch (e) {} },",
  "        };",
  "        if (opts.onStdout) {",
  "          createInterface({ input: child.stdout }).on(\"line\", (l) => {",
  "            try { opts.onStdout(l); } catch (e) { log(\"error\", e && e.message); }",
  "          });",
  "        }",
  "        if (opts.onStderr) {",
  "          createInterface({ input: child.stderr }).on(\"line\", (l) => {",
  "            try { opts.onStderr(l); } catch (e) { log(\"error\", e && e.message); }",
  "          });",
  "        }",
  "        child.on(\"exit\", (code, signal) => {",
  "          children.delete(child);",
  "          try { opts.onExit && opts.onExit(code, signal); } catch (e) { log(\"error\", e && e.message); }",
  "        });",
  "        child.on(\"error\", (e) => {",
  "          children.delete(child);",
  "          try { opts.onError && opts.onError(e); } catch (x) { log(\"error\", x && x.message); }",
  "        });",
  "        return job;",
  "      },",
  "      killAll() {",
  "        for (const c of children) { try { c.kill(); } catch (e) {} }",
  "        children.clear();",
  "      },",
  "    },",
  "    ai: {",
  "      registerTool(def) {",
  "        tools.push({",
  "          name: String(def.name),",
  "          description: String(def.description || \"\"),",
  "          parameters: def.parameters || { type: \"object\", properties: {} },",
  "        });",
  "      },",
  "    },",
  "    ui: {",
  "      notify(msg) { send({ t: \"emit\", token, panelId: \"__host\", event: \"notify\", payload: { msg: String(msg) } }); },",
  "    },",
  "  };",
  "  return api;",
  "}",
  "",
  "async function activate() {",
  "  ctx = makeCtx();",
  "  const entry = path.join(pluginDir, \"main.mjs\");",
  "  const mod = await import(pathToFileURL(entry).href);",
  "  if (typeof mod.activate !== \"function\") {",
  "    throw new Error(\"main.mjs 没有导出 activate(ctx)\");",
  "  }",
  "  await mod.activate(ctx);",
  "  if (tools.length) send({ t: \"tools\", token, tools });",
  "}",
  "",
  "async function runDisposers() {",
  "  // 逆序：后注册的先拆（后注册的往往依赖先注册的东西）",
  "  for (let i = disposers.length - 1; i >= 0; i--) {",
  "    try { await disposers[i](); } catch (e) { log(\"warn\", \"disposer 抛错: \" + (e && e.message)); }",
  "  }",
  "  disposers.length = 0;",
  "  try { ctx && ctx.process.killAll(); } catch (e) {}",
  "}",
  "",
  "async function handleCall(id, method, args) {",
  "  const scope = String(method).split(\".\")[0];",
  "  try {",
  "    let out;",
  "    if (scope === \"panel\") {",
  "      // panel.<panelId>.<method>",
  "      const parts = String(method).split(\".\");",
  "      const pid = parts[1];",
  "      const h = panelHandlers.get(pid);",
  "      const f = h && h[parts.slice(2).join(\".\")];",
  "      if (typeof f !== \"function\") throw Object.assign(new Error(\"面板方法不存在: \" + method), { code: \"not_found\" });",
  "      out = await f(args || {});",
  "    } else if (scope === \"command\") {",
  "      out = await ctx.commands.run(String(method).slice(8), args || {});",
  "    } else {",
  "      throw Object.assign(new Error(\"未知调用: \" + method), { code: \"bad_request\" });",
  "    }",
  "    send({ t: \"result\", token, id, ok: true, data: out === undefined ? null : out });",
  "  } catch (e) {",
  "    send({",
  "      t: \"result\", token, id, ok: false,",
  "      code: (e && e.code) || \"internal\",",
  "      err: String((e && e.message) || e).slice(0, 4000),",
  "    });",
  "  }",
  "}",
  "",
  "let activated = false;",
  "const rl = createInterface({ input: process.stdin });",
  "rl.on(\"line\", async (line) => {",
  "  const s = line.trim();",
  "  if (!s) return;",
  "  let m;",
  "  try { m = JSON.parse(s); } catch (e) { log(\"warn\", \"收到非 JSON 行，已忽略\"); return; }",
  "  if (!m || typeof m.t !== \"string\") return;",
  "",
  "  if (m.t === \"hello\") {",
  "    token = String(m.token || \"\");",
  "    if (!token) { send({ t: \"ready\", token: \"\", v: PROTOCOL, node: process.version }); process.exit(3); }",
  "    if (m.v !== PROTOCOL) {",
  "      log(\"error\", \"协议版本不匹配: \" + m.v + \" vs \" + PROTOCOL);",
  "      process.exit(4);",
  "    }",
  "    if (typeof m.workspace === \"string\") workspace = m.workspace;",
  "    send({ t: \"ready\", token, v: PROTOCOL, node: process.version });",
  "    return;",
  "  }",
  "  if (m.token !== token) return; // 不是本实例的消息，丢掉（空闲挂起重启后旧实例残留）",
  "",
  "  if (m.t === \"activate\") {",
  "    if (activated) return;",
  "    activated = true;",
  "    try { await activate(); } catch (e) {",
  "      log(\"error\", \"activate 失败: \" + String((e && e.stack) || e).slice(0, 3000));",
  "      send({ t: \"disposed\", token });",
  "      process.exit(5);",
  "    }",
  "    return;",
  "  }",
  "  if (m.t === \"call\") { await handleCall(String(m.id), String(m.method), m.args); return; }",
  "  if (m.t === \"dispose\") {",
  "    await runDisposers();",
  "    send({ t: \"disposed\", token });",
  "    // 给 stdout 一点时间排干再退",
  "    setTimeout(() => process.exit(0), 50);",
  "  }",
  "});",
  "",
  "process.on(\"unhandledRejection\", (e) => log(\"error\", \"unhandledRejection: \" + String(e)));",
  "process.on(\"uncaughtException\", (e) => log(\"error\", \"uncaughtException: \" + String(e)));",
  "",
];

export const BOOTSTRAP_SOURCE = LINES.join("\n");

/** 引导脚本的文件名（写盘位置由 `repo.ts` 的 `bootstrapPath` 决定）。 */
export const BOOTSTRAP_FILE = "bootstrap.mjs";
